"""Opt-in compact, synchronous v4 packets for input-only context methods.

The baseline guest ABI remains available on the same NRO for controlled A/B.
No call is deferred, cached or reordered. Generated adapters are unchanged.
"""
from pathlib import Path
import json,re

ROOT=Path(__file__).resolve().parents[1]
SRC=ROOT/'src/native_dxvk_com'

def methods():
    from generate_native_dxvk_com import is_custom
    inventory=json.loads((SRC/'com_inventory.json').read_text())
    result=[]
    for m in inventory['interfaces']['ID3D11DeviceContext']['methods']:
        if m['ret']!='void' or is_custom('ID3D11DeviceContext',m):continue
        if not ('Set' in m['name'] or m['name'].startswith('Draw')):continue
        if any(p['direction']!='in' or p['base'] in ('UINT64','ULONGLONG') for p in m['params']):continue
        assert len(m['params'])<=16
        result.append(m)
    return result

def generated_header():
    cases='\n'.join('    case '+str(m['index'])+': return '+str(len(m['params']))+'; /* '+m['name']+' */' for m in methods())
    return '''/* SPDX-License-Identifier: MIT; generated by native_dxvk_compact.py. */
#pragma once
#include "com_protocol.h"
#include <string.h>
#define SD_COM_COMPACT_MAGIC 0x53430000u
static inline int sd_com_compact_count(uint32_t interface_id,uint32_t method) {
    if(interface_id!=SD_COM_IF_ID3D11DeviceContext)return -1;
    switch(method) {
'''+cases+'''
    default:return -1;
    }
}
/* Caller must validate the whole 160-byte writable packet first, on every
 * invocation. Only whitelisted methods may omit unused argument storage. */
static inline int sd_com_wire_decode(struct sd_com_packet *p,const struct sd_com_packet *wire) {
    memcpy(p,wire,32);
    if(p->abi!=SD_COM_ABI)return 0;
    if(!p->reserved){memcpy(p->args,wire->args,128);return 1;}
    int n=sd_com_compact_count(p->interface_id,p->method);
    if(n<0||p->reserved!=(SD_COM_COMPACT_MAGIC|(uint32_t)n))return 0;
    memset(p->args,0,128);memcpy(p->args,wire->args,(unsigned)n*4);return 1;
}
static inline void sd_com_wire_encode(struct sd_com_packet *wire,const struct sd_com_packet *p) {
    if(p->reserved)memcpy(&wire->ret,&p->ret,12);
    else memcpy(wire,p,sizeof(*p));
}
'''

def guest(source):
    text=(source/'com_guest_vtables.inc').read_text()
    for m in methods():
        name='g_ID3D11DeviceContext_'+m['name']
        pos=text.index(name+'(');end=text.index('\n}',pos)
        body=text[pos:end]
        before='struct sd_com_packet packet = {SD_COM_ABI, proxy_token(This), SD_COM_IF_ID3D11DeviceContext, '+str(m['index'])+'};'
        assert body.count(before)==1,(name,'unexpected initializer')
        assert 'packet.high' not in body and 'proxy_output_' not in body,name
        assignments=[int(n) for n in re.findall(r'packet.args\[(\d+)\] =',body)]
        assert sorted(assignments)==list(range(len(m['params']))),name
        after='struct sd_com_packet packet;\n    packet.abi=SD_COM_ABI; packet.object=proxy_token(This);\n    packet.interface_id=SD_COM_IF_ID3D11DeviceContext; packet.method='+str(m['index'])+';\n    packet.ret=packet.fault=packet.aux=0; packet.reserved=0x53430000u|'+str(len(m['params']))+'u;'
        text=text[:pos]+body.replace(before,after)+text[end:]
    (source/'com_guest_vtables.inc').write_text(text,newline='\n')

def native(text):
    def change(before,after):
        nonlocal text
        assert text.count(before)==1,before
        text=text.replace(before,after)
    change('#include "com_protocol.h"','#include "com_protocol.h"\n#include "com_compact.h"')
    change('uint64_t discard_maps=0,discard_zero_bytes_skipped=0;','uint64_t discard_maps=0,discard_zero_bytes_skipped=0;\n    uint64_t compact_calls=0,compact_bytes_saved=0;')
    change('    void abort_map(uint32_t id) {','    void abort_map(uint32_t id) {')
    marker='        wine_nx_runtime_trace(line);\n    }\n    void abort_map'
    change(marker,'''        wine_nx_runtime_trace(line);
        std::snprintf(line,sizeof(line),"[SD-NDX-WIRE] compact-v1 calls=%llu native_copy_bytes_saved=%llu; synchronous, checked; gameplay FPS requires hardware comparison",
            (unsigned long long)compact_calls,(unsigned long long)compact_bytes_saved);
        wine_nx_runtime_trace(line);
    }
    void abort_map''')
    change('output=state.required_write<sd_com_packet>(uint32_t(address));sd_com_packet p=*output;\n        if(p.abi!=SD_COM_ABI||p.reserved)return int32_t(0xc000000du);',
           '''output=state.required_write<sd_com_packet>(uint32_t(address));sd_com_packet p;
        if(!sd_com_wire_decode(&p,output))return int32_t(0xc000000du);
        if(p.reserved){++state.compact_calls;state.compact_bytes_saved+=276-4*(p.reserved&0xffffu);}''')
    change('watch.result(p);*output=p;state.report();return 0;','watch.result(p);sd_com_wire_encode(output,&p);state.report();return 0;')
    return text

if __name__=='__main__':
    (SRC/'com_compact.h').write_text(generated_header(),newline='\n')
    print(json.dumps({'methods':len(methods()),'names':[m['name'] for m in methods()]}))
